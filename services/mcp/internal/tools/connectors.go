// ConnectorTools wraps the hub's /api/v1/connectors endpoints so an MCP
// client can list connectors, inspect one, and update it.
type ConnectorTools struct {
	HubURL     string
	HTTPClient *http.Client
}

// NewConnectorTools returns ConnectorTools pointed at hubURL, with a 10 s
// request timeout.
func NewConnectorTools(hubURL string) *ConnectorTools {
	return &ConnectorTools{
		HubURL:     hubURL,
		HTTPClient: &http.Client{Timeout: 10 * time.Second},
	}
}

func (c *ConnectorTools) ListConnectorsTool() mcp.Tool {
	return mcp.NewTool("list_connectors",
		mcp.WithDescription("List connectors with their status. Default page size: 50."),
		mcp.WithNumber("page", mcp.Description("Page number (1-based, default: 1)")),
		mcp.WithNumber("pageSize", mcp.Description("Page size (default: 50)")),
	)
}

func (c *ConnectorTools) GetConnectorTool() mcp.Tool {
	return mcp.NewTool("get_connector",
		mcp.WithDescription("Get detailed connector configuration and health"),
		mcp.WithString("name", mcp.Required(), mcp.Description("Connector name")),
	)
}

func (c *ConnectorTools) UpdateConnectorTool() mcp.Tool {
	return mcp.NewTool("update_connector",
		mcp.WithDescription("Update a connector. Omitted arguments are left unchanged; a present argument is applied. The hub's PUT accepts exactly these two fields — display_name and disabled — so there is nothing else to widen: the signature header and the webhook endpoint are fixed at create, and the signing secret is not a writable field (it is generated by the hub and returned once, by create_connector or the REST rotate-secret route, which has no MCP tool). An empty display_name is a no-op: the hub cannot blank a connector's label. Externally managed connectors (managedBy) are refused with 409, and the hub's 404/403 pass through unchanged. The connector ID (name argument) is the immutable identity and webhook endpoint; renames go through display_name."),
		mcp.WithString("name", mcp.Required(), mcp.Description("Connector ID (e.g. c-0c4b01e3) — exact match, no fuzzy lookup")),
		mcp.WithString("display_name", mcp.Description("New user-facing connector name (e.g. connector-forgejo-ainsel). Updates the connector's label and its channel name; webhook endpoints and the connector ID are unaffected.")),
		mcp.WithBoolean("disabled", mcp.Description("Pause (true) or resume (false) event delivery from this connector")),
	)
}

func (c *ConnectorTools) ListConnectors(ctx context.Context, req mcp.CallToolRequest) (*mcp.CallToolResult, error) {
	args, _ := req.Params.Arguments.(map[string]any)
	q := url.Values{}
	q.Set("page", strconv.Itoa(defaultArgInt(args, "page", 1)))
	q.Set("pageSize", strconv.Itoa(defaultArgInt(args, "pageSize", 50)))
	body, err := hubGet(ctx, c.HTTPClient, c.HubURL, "/api/v1/connectors?"+q.Encode())
	if err != nil {
		return mcp.NewToolResultError(fmt.Sprintf("failed to list connectors: %v", err)), nil
	}
	body = annotatePageMeta(body, "more connectors available — pass page=N to fetch the next page")
	return mcp.NewToolResultText(string(body)), nil
}

func (c *ConnectorTools) GetConnector(ctx context.Context, req mcp.CallToolRequest) (*mcp.CallToolResult, error) {
	name, ok := req.Params.Arguments.(map[string]any)["name"].(string)
	if !ok || name == "" {
		return mcp.NewToolResultError("name is required"), nil
	}
	body, err := hubGet(ctx, c.HTTPClient, c.HubURL, "/api/v1/connectors/"+name)
	if err != nil {
		return mcp.NewToolResultError(fmt.Sprintf("failed to get connector %s: %v", name, err)), nil
	}
	return mcp.NewToolResultText(string(body)), nil
}

func (c *ConnectorTools) UpdateConnector(ctx context.Context, req mcp.CallToolRequest) (*mcp.CallToolResult, error) {
	args, _ := req.Params.Arguments.(map[string]any)
	name, _ := args["name"].(string)
	if name == "" {
		return mcp.NewToolResultError("name is required"), nil
	}

	payload := map[string]any{}
	// Presence-based: a present argument is sent even when it is empty. The hub
	// reads an empty name as "no change" rather than "clear", so an explicit ""
	// here is a harmless no-op rather than a silent drop of the argument.
	if v, ok := args["display_name"].(string); ok {
		payload["name"] = v
	}
	if v, ok := args["disabled"].(bool); ok {
		payload["disabled"] = v
	}
	if len(payload) == 0 {
		return mcp.NewToolResultError("at least one of display_name or disabled must be provided"), nil
	}

	bodyData, err := json.Marshal(payload)
	if err != nil {
		return mcp.NewToolResultError(fmt.Sprintf("failed to encode request: %v", err)), nil
	}
	respBody, err := hubPut(ctx, c.HTTPClient, c.HubURL, "/api/v1/connectors/"+name, bytes.NewReader(bodyData))
	if err != nil {
		return mcp.NewToolResultError(fmt.Sprintf("failed to update connector %s: %v", name, err)), nil
	}
	return mcp.NewToolResultText(string(respBody)), nil
}

// CreateConnectorTool registers a webhook connector. The hub generates the
// HMAC signing secret itself and returns it once, in the create response —
// documented contract (docs/api-reference.md, openapi/hub.yaml) that the
// console relies on to show the operator the value to paste into the source.
// The tool passes the hub body through verbatim, so that one response carries
// the secret into the session; every read path (list, get, update) masks it.
func (c *ConnectorTools) CreateConnectorTool() mcp.Tool {
	return mcp.NewTool("create_connector",
		mcp.WithDescription("Create a webhook connector: an inbound endpoint under the platform's external URL (/webhooks/<id>) that receives events from an external system and verifies them with an HMAC signature. The hub generates the signing secret, stores it in a Kubernetes Secret, and returns it once in this result as webhookSecretValue — copy it into the source's webhook signing config now, because no later read returns it and this result may end up in a logged session. The hub has one connector kind, the generic webhook receiver: Forgejo and GitHub arrive as plugins, not as connector kinds, and a connector a plugin stamped (managedBy) refuses these writes with 409. The gateway operator then rolls out the receiver Deployment, Service and ingress path for the new id. Requires a groupId the caller has write access to on hubs with access control enabled."),
		mcp.WithString("name", mcp.Required(), mcp.Description("Display name for the new connector (e.g. connector-sentry). The hub assigns the c-prefixed connector id and returns it in the response.")),
		mcp.WithString("groupId", mcp.Description("Group to assign the connector to; must be a group the caller has write access to. Required on hubs with access control enabled.")),
		mcp.WithString("signature_header", mcp.Description("HTTP header the source signs with, e.g. X-Sentry-Auth-Signature or X-Forgejo-Signature. Defaults to X-Hub-Signature-256.")),
	)
}

func (c *ConnectorTools) CreateConnector(ctx context.Context, req mcp.CallToolRequest) (*mcp.CallToolResult, error) {
	args, _ := req.Params.Arguments.(map[string]any)
	name, _ := args["name"].(string)
	if strings.TrimSpace(name) == "" {
		return mcp.NewToolResultError("name is required"), nil
	}

	payload := map[string]any{"name": name}
	if v, _ := args["groupId"].(string); v != "" {
		payload["groupId"] = v
	}
	if v, ok := args["signature_header"].(string); ok {
		// Presence-based, like the other optional fields. The hub treats an empty
		// header as "not set" and applies its own default, so "" is a no-op rather
		// than a way to store an empty header.
		payload["signatureHeader"] = v
	}

	bodyData, err := json.Marshal(payload)
	if err != nil {
		return mcp.NewToolResultError(fmt.Sprintf("failed to encode request: %v", err)), nil
	}
	respBody, err := hubPost(ctx, c.HTTPClient, c.HubURL, "/api/v1/connectors", bytes.NewReader(bodyData))
	if err != nil {
		return mcp.NewToolResultError(fmt.Sprintf("failed to create connector: %v", appendGroupIDHint(err))), nil
	}
	return mcp.NewToolResultText(string(respBody)), nil
}

func (c *ConnectorTools) DeleteConnectorTool() mcp.Tool {
	return mcp.NewTool("delete_connector",
		mcp.WithDescription("Delete a connector. This is final: the connector, its webhook endpoint and its stored signing secret are removed, so events from the external system stop arriving — the source keeps signing against a secret that no longer exists and posts to a path that now 404s. Nothing is archived and there is no undo. Externally managed connectors (managedBy, e.g. created by a plugin) are refused with 409. The hub's 404/403 pass through unchanged."),
		mcp.WithString("name", mcp.Required(), mcp.Description("Connector ID (e.g. c-0c4b01e3) — exact match; display names are not resolved")),
	)
}

func (c *ConnectorTools) DeleteConnector(ctx context.Context, req mcp.CallToolRequest) (*mcp.CallToolResult, error) {
	args, _ := req.Params.Arguments.(map[string]any)
	name, _ := args["name"].(string)
	if strings.TrimSpace(name) == "" {
		return mcp.NewToolResultError("name is required"), nil
	}
	if _, err := hubDelete(ctx, c.HTTPClient, c.HubURL, "/api/v1/connectors/"+name); err != nil {
		return mcp.NewToolResultError(fmt.Sprintf("failed to delete connector %s: %v", name, err)), nil
	}
	return mcp.NewToolResultText(fmt.Sprintf("connector %s deleted", name)), nil
}
